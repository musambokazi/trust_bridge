export const defaultPhoneRegion = phoneRegions.find(([iso]) => iso === "ZA")!;

export function normalizePhone(input: string, region = defaultPhoneRegion): string | null {
  const digits = input.replace(/[\s().-]/g, "");
  const [, , dial, trunkZero] = region;
  if (!/^\+?\d+$/.test(digits)) return null;
  let local = digits;
  if (digits.startsWith("+")) {
    if (!digits.startsWith("+" + dial)) return null;
    local = digits.slice(dial.length + 1);
  }
  if (trunkZero && local.startsWith("0")) local = local.slice(1);
  return local.length >= 6 && dial.length + local.length <= 15 ? "+" + dial + local : null;
}
